/** The languages of the built-in texts. English is the fallback. */
export const LANGUAGES = ["en", "de", "it", "es", "pt", "fr", "pl"] as const;

export type Language = (typeof LANGUAGES)[number];

/**
 * The widget language for a language tag such as "it", "it-IT" or "pt_BR":
 * its primary subtag, if the widget has that language. Else null.
 */
export function toLanguage(tag: unknown): Language | null {
  if (typeof tag !== "string") return null;
  const primary = tag.trim().split(/[-_]/)[0].toLowerCase();
  return (LANGUAGES as readonly string[]).includes(primary) ? (primary as Language) : null;
}

